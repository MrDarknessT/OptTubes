package ru.grain.monitor

import java.util.Random

class Simulator(example: IntArray) {
    private val example = example.copyOf()
    private var random = Random(96)
    private val overrides = IntArray(96) { -1 }
    private val greenPulse = BooleanArray(96)

    init { require(example.size == 96 && example.all { it in 0..3 }) }

    fun reset() {
        random = Random(96)
        overrides.fill(-1)
        greenPulse.fill(false)
    }

    fun override(i: Int, code: Int) {
        require(i in 0 until 96 && code in -1..3)
        overrides[i] = code
    }

    fun overrideAt(i: Int): Int = overrides[i]

    fun pulse(i: Int) {
        overrides[i] = -1
        greenPulse[i] = true
    }

    /** null means no complete packet received, not an all-zero frame. */
    fun next(scenario: Int, frame: Long): IntArray? {
        require(scenario in names.indices && frame >= 0)
        val ms = frame * SensorFilter.SAMPLE_MS
        if (scenario == 10 && ms % 12000 in 4000L until 8000L) return null

        return IntArray(96) { i ->
            // A short green pulse every 300..900 ms. 90 ms width tolerates timer jitter.
            val period = 10 + i % 21
            var code = if ((frame + i * 7) % period < 3) 1 else 0
            when (scenario) {
                0 -> {
                    val phase = ms % 24000
                    if (phase in 4000L until 12000L && i in 12..15) code = 2
                    if (phase in 8000L until 18000L && i in 48..51) code = 3
                    if (phase in 16000L until 21000L && i >= 80) code = 0
                    if (phase >= 21000) code = 1
                }
                2 -> if (ms % 3000 < 300 && i % 5 == 0) code = 2 + i % 2
                3 -> if (i in 12..15) code = 2
                4 -> if (i in 48..51) code = 3
                5 -> code = 0
                6 -> if (i < 12) code = if (ms % 10000 < 5000) 2 else 1
                7 -> code = if ((frame + i) % 10 < 7) 2 else 1
                8 -> code = random.nextInt(4)
                9 -> code = example[i]
                11 -> code = 2
                12 -> code = if ((frame + i) % 55 < 3) 1 else 0
            }
            if (overrides[i] >= 0) code = overrides[i]
            if (greenPulse[i]) {
                code = 1
                greenPulse[i] = false
            }
            code
        }
    }

